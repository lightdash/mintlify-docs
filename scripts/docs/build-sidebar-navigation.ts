import { readFile, writeFile } from 'node:fs/promises';
import { parseFrontmatter } from './lib/frontmatter.ts';
import { apiSidebarEntries, type ApiSchema } from './lib/sidebar-navigation.ts';

interface Entry { title: string; href: string; parents: string[] }
interface Group { group?: string; root?: string; pages?: (string | Group)[]; openapi?: string }
interface Tab { tab: string; pages?: (string | Group)[]; groups?: Group[] }

const config = JSON.parse(await readFile('docs.json', 'utf8')) as {
  navigation: { tabs: Tab[] };
};
const tabs: { title: string; entries: Entry[] }[] = [];
for (const tab of config.navigation.tabs) {
  const entries: Entry[] = [];
  async function addPage(slug: string, parents: string[], label?: string) {
    if (/^https?:/.test(slug)) return;
    const content = await readFile(`${slug}.mdx`, 'utf8');
    const { fields, hidden } = parseFrontmatter(content);
    if (hidden) return;
    entries.push({
      title: label ?? fields.get('sidebarTitle') ?? fields.get('title') ?? slug,
      href: `/${slug}`,
      parents,
    });
  }
  async function visit(items: (string | Group)[], parents: string[] = []) {
    for (const item of items) {
      if (typeof item === 'string') await addPage(item, parents);
      else {
        if (item.root) await addPage(item.root, parents, item.group);
        const context = item.group ? [...parents, item.group] : parents;
        await visit(item.pages ?? [], context);
        if (item.openapi) {
          const response = await fetch(item.openapi);
          if (!response.ok) throw new Error(`Cannot read sidebar OpenAPI source: ${response.status}`);
          entries.push(...apiSidebarEntries(await response.json() as ApiSchema, context));
        }
      }
    }
  }
  await visit(tab.pages ?? tab.groups ?? []);
  tabs.push({ title: tab.tab, entries });
}
// One entry per line, so a diff shows only the entries that changed.
const serialized = `[\n${tabs.map((tab) => `{"title":${JSON.stringify(tab.title)},"entries":[\n${tab.entries.map((entry) => JSON.stringify(entry)).join(',\n')}\n]}`).join(',\n')}\n]`;
const output = `/* Generated by aube run build:sidebar-navigation. */\nwindow.lightdashSidebarNavigation = ${serialized};\nwindow.dispatchEvent(new Event('lightdash:navigation-ready'));\n`;
if (process.argv.includes('--check')) {
  const current = await readFile('sidebar-navigation.js', 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error;
    return undefined;
  });
  if (current !== output) {
    throw new Error('Sidebar titles changed. Run aube run build:sidebar-navigation.');
  }
} else {
  await writeFile('sidebar-navigation.js', output);
}
